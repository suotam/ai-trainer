  double rky,
  double rfx,
  double rfy,
  double lex,
  double ley,
  double lhx,
  double lhy,
  double rex,
  double rey,
  double rhx,
  double rhy,
) => [
  _p(hx, hy),
  _p(nx, ny),
  _p(px, py),
  _p(lkx, lky),
  _p(lfx, lfy),
  _p(rkx, rky),
  _p(rfx, rfy),
  _p(lex, ley),
  _p(lhx, lhy),
  _p(rex, rey),
  _p(rhx, rhy),
];

List<Offset> _forearm(
  double ex,
  double ey,
  double wx,
  double wy,
  double fx,
  double fy,
) => [_p(ex, ey), _p(wx, wy), _p(fx, fy)];

