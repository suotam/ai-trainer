Offset _p(double x, double y) => Offset(x / 100, y / 100);

// Boční postava: head, neck, hip, knee, foot, elbow, hand.
List<Offset> _side(
  double hx,
  double hy,
  double nx,
  double ny,
  double px,
  double py,
  double kx,
  double ky,
  double fx,
  double fy,
  double ex,
  double ey,
  double dx,
  double dy,
) => [
  _p(hx, hy),
  _p(nx, ny),
  _p(px, py),
  _p(kx, ky),
  _p(fx, fy),
  _p(ex, ey),
  _p(dx, dy),
];

// Čelní postava: head, neck, hip, lKnee, lFoot, rKnee, rFoot, lElbow,
// lHand, rElbow, rHand.
